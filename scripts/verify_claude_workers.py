def check(name, passed, detail, unknown=False):
    return {"name": name, "status": "pass" if passed else "unknown" if unknown else "fail", "detail": detail}


def response_failed(event):
    response = event.get("tool_response", {})
    return (event.get("is_error") is True or isinstance(response, dict) and
            (response.get("is_error") is True or response.get("exit_code") not in (None, 0)
             or response.get("interrupted") is True))


def admitted(capture):
    if capture.get("delegate_exit_code") != 0:
        return False
    try:
        value = json.loads(capture.get("delegate_stdout", "")) if capture.get("delegate_stdout", "").strip() else {}
    except ValueError:
        return False
    return (value.get("decision") != "block" and value.get("continue") is not False and
            value.get("hookSpecificOutput", {}).get("permissionDecision") != "deny")


def native_completion(stream, session, actor, launch_call):
    """Only structured host events count, never agent-authored report text."""
    return [row for row in stream if actor and launch_call and row.get("type") == "system"
            and row.get("subtype") == "task_notification" and row.get("session_id") == session
            and row.get("task_id") == actor and row.get("tool_use_id") == launch_call
            and row.get("status") == "completed" and isinstance(row.get("summary"), str)
            and row["summary"].strip()]


def candidate_selections(stream, session):
    """Each init is a snapshot; repeated snapshots are not duplicate installs."""
    return [[p for p in row.get("plugins", []) if isinstance(p, dict)
             and str(p.get("name", "")).split("@")[0] == "taskplane"]
            for row in stream if row.get("type") == "system" and row.get("subtype") == "init"
            and row.get("session_id") == session and isinstance(row.get("plugins"), list)]


def overlapping_workers(first, rows):
    """Use actual stop observations, not delayed controller reconciliation."""
    stopped = first.get("stop_observation", {}).get("observed_at")
    return [row for row in rows if row.get("task_id") == "CW-LIVE-B"
            and first.get("claimed_at") and stopped and row.get("claimed_at")
            and row.get("stop_observation", {}).get("observed_at")
            and max(first["claimed_at"], row["claimed_at"])
            < min(stopped, row["stop_observation"]["observed_at"])]


def inspect_live(workspace, original, plugin, captures, native, stream, process, retry):
    """Read corroborating state and host evidence; never repair/mutate it."""
    states, errors = [], []
    for path in (workspace / ".taskplane").glob("workflow-*.json"):
        if path.name.endswith(".initialized.json"):
            continue
        try:
            db = load(path)
            if db.get("root") == process["session_id"]:
                states.extend(db.get("runs", {}).values())
        except (OSError, ValueError) as exc:
            errors.append(str(exc))
    states = [s for s in states if s.get("root") == process["session_id"] and s.get("workspace") == str(workspace)]
    checks = [check("host process completed", process["exit_code"] == 0 and not process["timed_out"], process),
              check("one fresh root workflow", len(states) == 1, {"runs": [s.get("run") for s in states], "errors": errors})]
    state = states[0] if len(states) == 1 else {}
    rows = list(state.get("workers", {}).values())
    results = state.get("task_results", {})
    staged = fingerprint(plugin)
    expected = staged["member_sha256"]
    checks.append(check("automatic candidate hooks", bool(captures) and all(
        c["runtime"]["root"] == str(plugin) and c["runtime_unchanged"] and
        c["runtime"]["member_sha256"] == expected and not c["capability_fixture"] for c in captures),
        {"count": len(captures), "root": str(plugin)}))
    selected = []
    for task_id in ("CW-LIVE-A", "CW-LIVE-B"):
        result = results.get(task_id, {})
        matches = [r for r in rows if r.get("grant_id") == result.get("grant") and r.get("task_id") == task_id]
        row = matches[0] if len(matches) == 1 else {}
        selected.append(row)
        actor = row.get("worker_id")
        events = [c for c in captures if actor and c["input"].get("agent_id") == actor]
        pres = {c["input"].get("tool_use_id"): c for c in events if c["event"] == "PreToolUse"}
        posts = {c["input"].get("tool_use_id"): c for c in events if c["event"] == "PostToolUse"}
        ordinary = [call for call in pres.keys() & posts.keys() if call and
                    pres[call]["input"].get("tool_name") in {"Read", "Bash"} and
                    "flow " not in str(pres[call]["input"].get("tool_input", {})) and
                    admitted(pres[call]) and admitted(posts[call]) and not response_failed(posts[call]["input"])]
        claims, rewrites, completed_context = [], [], []
        for call, before in pres.items():
            cmd = before["input"].get("tool_input", {}).get("command", "")
            if call in posts and admitted(before) and "--operation claim" in cmd and row.get("grant_id", "missing") in cmd:
                try:
                    returned = json.loads(posts[call]["input"].get("tool_response", {}).get("stdout", ""))
                    if returned.get("grant_id") == row.get("grant_id") and returned.get("task_id") == task_id:
                        claims.append(call)
                except (ValueError, TypeError):
                    pass
            if call in posts and "flow context" in cmd and task_id in cmd:
                try:
                    returned = json.loads(posts[call]["input"].get("tool_response", {}).get("stdout", ""))
                    if returned.get("done") is True and returned.get("remaining_required") == 0:
                        completed_context.append(call)
                except (ValueError, TypeError):
                    pass
            try:
                output = json.loads(before["delegate_stdout"])
            except ValueError:
                continue
            rewritten = output.get("hookSpecificOutput", {}).get("updatedInput", {}).get("command", "")
            if "--invocation-ref" in rewritten and call in posts:
                rewrites.append(call)
        handback_calls = [call for call, c in pres.items() if c["input"].get("tool_name") == "SubagentHandback" and admitted(c)]
        stops = [c for c in events if c["event"] == "SubagentStop"]
        handback = row.get("handback", {})
        notifications = native_completion(stream, process["session_id"], actor, row.get("call_id"))
        delivered = handback.get("status") == "delivered" or handback.get("state") == "delivered" or bool(handback.get("delivered_at"))
        receipt = row.get("context_receipt")
        proof = row.get("hook_readiness", {})
        runtime = row.get("expected_runtime", {})
        runtime_match = runtime.get("root") == str(plugin) and bool(runtime.get("member_sha256")) and all(
            expected.get(k) == v and v for k, v in runtime.get("member_sha256", {}).items())
        checks.extend([
            check(task_id + " prepared/claim/context", bool(row.get("prepared_at") and row.get("call_id") and
                  row.get("claimed_at") and receipt and claims and rewrites and completed_context),
                  {"grant": row.get("grant_id"), "worker": actor, "launch_call": row.get("call_id"),
                   "claim_calls": claims, "rewritten_calls": rewrites, "complete_context_calls": completed_context,
                   "context_receipt": receipt}),
            check(task_id + " ordinary automatic hook pair", bool(ordinary and proof.get("matched_call") and runtime_match),
                  {"calls": ordinary, "readiness": proof, "expected_runtime": runtime}),
            check(task_id + " result delivery", bool((handback_calls or notifications) and delivered),
                  {"calls": handback_calls, "notifications": notifications, "controller": handback},
                  unknown=bool((handback_calls or notifications) and not delivered)),
            check(task_id + " independent terminal and root acceptance", bool(stops and row.get("terminal_status") in {"completed", "idle"}
                  and row.get("state") == "accepted" and result.get("accepted_at") and result.get("worker_id") == actor
                  and actor != state.get("root") and not row.get("revoked_at") and not row.get("identity_conflict")),
                  {"terminal": row.get("terminal_status"), "state": row.get("state"), "result": result,
                   "stop_events": [c["input"] for c in stops]}),
        ])
        suffix, source, trigger = ("a", "averages.py", "average") if task_id.endswith("A") else ("b", "settings.py", "port")
        output_path = workspace / f".taskplane/review-{suffix}.md"
        try:
            body = read_regular(output_path, 32768).decode()
            useful = len(body.strip()) >= 100 and source in body and trigger in body.lower()
            manifest = result.get("manifest", {})
            expected_digest = manifest.get(str(output_path.relative_to(workspace)))
            if isinstance(expected_digest, dict):
                expected_digest = expected_digest.get("sha256", expected_digest.get("digest"))
            useful = useful and expected_digest == digest(body.encode())
            detail = {"path": str(output_path), "sha256": digest(body.encode()), "bytes": len(body.encode()),
                      "accepted_fingerprint": expected_digest}
        except (OSError, ValueError, UnicodeError) as exc:
            useful, detail = False, {"error": str(exc)}
        checks.append(check(task_id + " distinct useful scoped output", useful, detail))
    actors = [r.get("worker_id") for r in selected]
    checks.append(check("distinct native workers", all(actors) and len(set(actors)) == 2, actors))
    # Any B attempt overlapping A establishes actual concurrent ownership even
    # when B's first deliberate failing attempt is followed by a fresh retry.
    overlap = overlapping_workers(selected[0], rows)
    checks.append(check("observed concurrent worker lifetimes", bool(overlap), [r["grant_id"] for r in overlap]))
    schema = native["handback_schemas"]
    completion_contract = bool(native.get("completion_notifications")) and all(
        native_completion(stream, process["session_id"], row.get("worker_id"), row.get("call_id"))
        for row in selected)
    supported_delivery = bool(schema) or completion_contract
    checks.append(check("fresh host result delivery contract", supported_delivery,
                        {"handback_schemas": schema, "native_completion": completion_contract},
                        unknown=not supported_delivery))
    selections = candidate_selections(stream, process["session_id"])
    checks.append(check("single candidate plugin selected", bool(selections) and all(
        len(group) == 1 and group[0].get("path") == str(plugin) for group in selections),
        selections, unknown=not selections))
    if workspace != original:
        parent = [s for s in native["sources"] if Path(s["path"]).stem == process["session_id"]]
        initial = [c["input"] for c in captures if c["event"] == "SessionStart"
                   and c["input"].get("session_id") == process["session_id"] and not c["input"].get("agent_id")]
        selected_paths = {c.get("transcript_path") for c in initial if c.get("cwd") == str(original)}
        child_cwds = {c["input"].get("cwd") for c in captures if c["input"].get("agent_id") in actors}
        checks.append(check("worktree execution with original project transcript", bool(parent) and
                            bool(selected_paths) and all(p["path"] in selected_paths for p in parent) and
                            child_cwds == {str(workspace)},
                            {"parent_sources": parent, "initial_root_events": initial,
                             "execution_workspace": str(workspace), "child_cwds": sorted(str(p) for p in child_cwds)}))
    if retry:
        current = selected[1]
        previous = [r for r in rows if r.get("task_id") == "CW-LIVE-B" and r.get("grant_id") != current.get("grant_id")]
        failure_calls = [c for c in captures if c["event"] == "PostToolUse" and response_failed(c["input"])
                         and c["input"].get("agent_id") in {r.get("worker_id") for r in previous}]
        injected = {c["input"].get("tool_use_id") for c in captures if c["event"] == "PreToolUse"
                    and c["input"].get("agent_id") in {r.get("worker_id") for r in previous}
                    and "raise SystemExit(17)" in c["input"].get("tool_input", {}).get("command", "")}
        failure_results = [r for r in native.get("results", []) if r["result"].get("tool_use_id") in injected
                           and r["result"].get("is_error") is True]
        retained = any(r.get("terminal_status") and r.get("state") != "accepted" and r.get("attempt", 0) < current.get("attempt", 0)
                       for r in previous)
        checks.append(check("real failed attempt and fresh bounded retry", bool(retained and (failure_calls or failure_results) and
                            current.get("retry_reason") and len(previous) == 1),
                            {"previous_attempts": previous, "failure_events": [c["input"] for c in failure_calls],
                             "native_failure_results": failure_results,
                             "retry_grant": current.get("grant_id"), "retry_reason": current.get("retry_reason"),
                             "classification": "Real command fault injection; host termination status is reported independently."}))
    return {"status": "pass" if all(c["status"] == "pass" for c in checks) else "fail",
            "checks": checks, "controller_runs": states, "read_errors": errors}


