    # Each scenario starts a new Claude session and a new, isolated workflow.
    for fixture in prepared["fixtures"]:
        name, retry = fixture["name"], fixture["failure_retry"]
        preparation_dir = Path(fixture["directory"])
        scenario_dir = preparation_dir / ("attempt-" + uuid.uuid4().hex)
        scenario_dir.mkdir()
        capture = scenario_dir / "hooks"
        capture.mkdir()
        plugin = Path(fixture["plugin"])
        original, workspace = Path(fixture["original_project"]), Path(fixture["workspace"])
        if not all(p.is_relative_to(folder) for p in (plugin, original, workspace, preparation_dir)):
            raise ValueError("Prepared fixture paths escape their recorded directory")
        if fingerprint(plugin) != fixture.get("staged_candidate"):
            raise ValueError("Prepared staged runtime changed")
        if digest(read_regular(workspace / fixture["probe_file"])) != fixture.get("probe_sha256"):
            raise ValueError("Prepared fixture source probe changed")
        if any(digest(read_regular(workspace / p)) != expected for p, expected in fixture["input_sha256"].items()):
            raise ValueError("Prepared fixture source or task/scope input changed")
        if digest(read_regular(preparation_dir / "capture.py")) != fixture["capture_script_sha256"]:
            raise ValueError("Prepared hook capture script changed")
        if not (workspace / ".taskplane/workspace-binding.json").is_file():
            raise ValueError(f"Prepared workspace needs independent probe/bind before launch: {workspace}")
        for path in (workspace / ".taskplane").glob("workflow-*.json"):
            if path.name.endswith(".initialized.json"):
                continue
            db = load(path)
            if any(r.get("state") in {"prepared", "launch_pending", "bootstrapping", "running", "cancel_requested", "unknown"}
                   for state in db.get("runs", {}).values() for r in state.get("workers", {}).values()):
                raise ValueError("Prepared workspace retains live or unknown worker ownership; reconcile it before any new session")
        config_path = preparation_dir / "proxy-config.json"
        config = load(config_path)
        if digest(json.dumps({k: config[k] for k in ("commands", "probe")}, sort_keys=True).encode()) != fixture["delegate_config_sha256"]:
            raise ValueError("Prepared hook delegate configuration changed")
        config["capture"] = str(capture)
        save(config_path, config)
        git = fixture["git_setup"]
        print(json.dumps({"running": name, "evidence_directory": str(scenario_dir)}), flush=True)
        process = launch(args.claude, plugin, original, scenario_dir,
                         live_prompt(plugin, workspace, original, retry), args.timeout, args.model, workspace)
        captures = [load(p) for p in capture.glob("*.json")]
        stream, errors = stream_rows(scenario_dir / "stream.jsonl")
        native, _ = transcript_evidence(captures, process["session_id"])
        scenario = {"name": name, "process": process, "workspace": str(workspace), "original_project": str(original),
                    "git_setup": git, "staged_candidate": fingerprint(plugin),
                    "observations": capture_summary(captures, native, stream), "native_transcripts": native,
                    "capture_errors": errors,
                    "verification": inspect_live(workspace, original, plugin, captures, native, stream, process, retry)}
        if errors or native["errors"]:
            scenario["verification"]["status"] = "fail"
        report["scenarios"].append(scenario)
        report["status"] = "pass" if len(report["scenarios"]) == 2 and all(
            s["verification"]["status"] == "pass" for s in report["scenarios"]) else "fail"
        save(args.output, report)  # Preserve a completed scenario even if the next one fails.
        if scenario["verification"]["status"] != "pass":
            break  # Resolve the first blocker before spending another host session.
    report["e2e_status"] = report["status"]


