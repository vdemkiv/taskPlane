"""Capture fresh Claude capabilities and verify scoped native worker evidence.

No controller mutations or hook-shaped fixture events are generated by this
program. Claude executes the workflow through the candidate's real hooks. A
separate, explicitly labelled capability probe tests harmless updatedInput use.
"""
